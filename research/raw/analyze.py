def load_corpus():
    docs = {}
    for f in sorted(glob.glob(TXT + '/b*.txt')):
        docs[os.path.basename(f)[:-4]] = open(f, encoding='utf-8').read()
    vm = json.load(open('C:/Users/kevin/workspace/fukuoka/research/raw/videos_meta.json', encoding='utf-8'))
    for v in vm:
        docs['VID_' + v['key']] = (v.get('title') or '') + '\n' + (v.get('desc') or '')
    return docs


docs = load_corpus()
# de-dup identical docs (mimigo/mimihan mirror)
seen, uniq = {}, {}
for k, t in docs.items():
    h = hash(t[:4000])
    if h in seen:
        continue
    seen[h] = k
    uniq[k] = t
docs = uniq

rows = []
for name, (area, aliases) in SPOTS.items():
    hit_docs, total = [], 0
    for k, t in docs.items():
        c = sum(t.count(a) for a in aliases)
        if c:
            hit_docs.append(k)
            total += c
    rows.append(dict(name=name, area=area, docs=len(hit_docs),
                     mentions=total, hit=hit_docs))

rows.sort(key=lambda r: (-r['docs'], -r['mentions']))
json.dump(dict(n_docs=len(docs), rows=rows),
          open('C:/Users/kevin/workspace/fukuoka/research/spot_stats.json', 'w', encoding='utf-8'),
          ensure_ascii=False, indent=1)

print('corpus docs (deduped):', len(docs))
print('rank  docs mentions  area          name')
for i, r in enumerate(rows, 1):
    print('%3d   %3d  %5d      %-12s %s' % (i, r['docs'], r['mentions'], r['area'], r['name']))
