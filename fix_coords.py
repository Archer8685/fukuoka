def main():
    applied, notfound = 0, []
    seen = set()
    for path in sorted(glob.glob("data/*.json")):
        with open(path, encoding="utf-8") as f:
            places = json.load(f)
        changed = False
        for p in places:
            f = FIX.get(p["name"])
            if not f:
                continue
            seen.add(p["name"])
            lat, lng, st = f
            old = (p.get("lat"), p.get("lng"))
            p["lat"], p["lng"], p["coord_status"] = lat, lng, st
            applied += 1
            changed = True
            print(f"  {st:6s} {p['name']:26s} {old} -> ({lat}, {lng})")
        if changed:
            with open(path, "w", encoding="utf-8") as f:
                json.dump(places, f, ensure_ascii=False, indent=1)
                f.write("\n")
    notfound = sorted(set(FIX) - seen)
    print(f"\n套用 {applied} 筆")
    if notfound:
        print("⚠️ 表裡有但 data 裡找不到的名稱（可能改名了，請更新這支檔案）：")
        for n in notfound:
            print("   -", n)


if __name__ == "__main__":
    main()
